/**
 * Writes supabase/seed.sql: today's built-in photos and layout as database rows, so the
 * site looks the same on the first day the admin panel is used.
 *
 *   node scripts/seed-media.ts          (regenerates supabase/seed.sql)
 *
 * Local: `npx supabase db reset` applies the migration and then this seed.
 * Production: run supabase/seed.sql once in the Supabase SQL editor after the migration.
 * It is safe to run twice (ON CONFLICT DO NOTHING); it never overwrites admin edits.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { tlobLibrary } from "../lib/library.ts";
import { heroPhoto, onStage, photos, type Photo } from "../lib/photos.ts";
import { site } from "../lib/site.ts";
import { tagline } from "../lib/content.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const pathOf = (ph: Photo) => ph.src.slice(base.length);

/** Every photo the site knows, keyed by path, with its children flag. */
const all = new Map<string, Photo>();
for (const ph of Object.values(photos)) all.set(pathOf(ph), ph);
for (const l of tlobLibrary) {
  const p = `/images/tlob/${l.file}`;
  all.set(p, { src: p, w: l.w, h: l.h, alt: l.alt, ...(l.showsChildren ? { showsChildren: true as const } : {}) });
}

const lines: string[] = [
  "-- Generated by scripts/seed-media.ts. Do not edit by hand.",
  "begin;",
];

for (const [p, ph] of all) {
  lines.push(
    `insert into public.media (kind, source, path, alt, width, height, shows_children) values ('image', 'static', ${q(p)}, ${q(ph.alt)}, ${ph.w}, ${ph.h}, ${ph.showsChildren ? "true" : "false"}) on conflict do nothing;`,
  );
}

const sections: Record<string, string[]> = {
  home_hero: [pathOf(heroPhoto)],
  home_on_stage: onStage.photos.map(pathOf),
  about: [pathOf(photos.instructorMagenta)],
  gallery: [
    ...[
      photos.goldStage, photos.ganesha, photos.stageLights, photos.magentaSarees, photos.orangeStage, photos.whiteJackets,
      photos.backstage, photos.stagePose, photos.outdoor, photos.trophies2024, photos.trophiesGroup, photos.trophiesHallway,
      photos.boys, photos.saree, photos.instructorMagenta, photos.instructor,
    ].map(pathOf),
    ...tlobLibrary.filter((l) => !l.section).map((l) => `/images/tlob/${l.file}`),
  ],
  on_screen: tlobLibrary.filter((l) => l.section === "screen").map((l) => `/images/tlob/${l.file}`),
  recognition: tlobLibrary.filter((l) => l.section === "recognition").map((l) => `/images/tlob/${l.file}`),
  earlier_website: tlobLibrary.filter((l) => l.section === "archive").map((l) => `/images/tlob/${l.file}`),
};

/** Starting grid size from the photo's shape: tall photos two rows, wide ones two columns (gallery grids only). */
function spans(section: string, ph: Photo) {
  if (!["gallery", "on_screen", "earlier_website"].includes(section)) return { col: 1, row: 1 };
  const r = ph.h / ph.w;
  return { col: r < 0.62 ? 2 : 1, row: r > 1.2 ? 2 : 1 };
}

for (const [section, paths] of Object.entries(sections)) {
  paths.forEach((p, i) => {
    if (!all.has(p)) throw new Error(`${section}: ${p} is not a known photo`);
    lines.push(
      `insert into public.placements (media_id, section, position, col_span, row_span) select id, ${q(section)}, ${i}, ${spans(section, all.get(p)!).col}, ${spans(section, all.get(p)!).row} from public.media where path = ${q(p)} on conflict do nothing;`,
    );
  });
}

const settings: Record<string, unknown> = {
  phone: site.phone,
  phone_display: site.phoneDisplay,
  email: site.email,
  hero_headline: "Learn Bollywood from a film-industry performer.",
  tagline,
  announcement: "",
  children_photos_cleared: true,
};
for (const [k, v] of Object.entries(settings)) {
  lines.push(`insert into public.site_settings (key, value) values (${q(k)}, ${q(JSON.stringify(v))}::jsonb) on conflict do nothing;`);
}

lines.push("commit;", "");
const out = path.join(import.meta.dirname, "..", "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${all.size} media, ${Object.values(sections).flat().length} placements, ${Object.keys(settings).length} settings`);
